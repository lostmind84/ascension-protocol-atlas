#!/usr/bin/env python3
"""Lift the result-code string tables the handlers index by a packet value.

Idiom in the decompiled handlers (build/ghidra/handlers-c):

    if (code < 5) { name = (&PTR_s_CREATE_LISTING_OK_10b40440)[code * 2]; ... }

The table at that address is N pairs of (char*, length): the enum the u32 in the packet
means, in order, with the client's own strings. Recorded per opcode with the bound the
handler checks, so a fiche can list the values of its result field.

  python3 tools/extract/result_tables.py <c dir> <Extensions.dll> --build <id> --out <file>
"""

import argparse
import hashlib
import importlib.util
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TABLE = re.compile(r"\(&PTR_s_\w+?_(10b[0-9a-f]{5})\)\[(\w+) \* 2\]")
BOUND = re.compile(r"if \((\w+) < (0x[0-9a-f]+|\d+)\)")


def load_image(path):
    spec = importlib.util.spec_from_file_location("opcode_names", os.path.join(HERE, "opcode_names.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.Image(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("cdir")
    parser.add_argument("dll")
    parser.add_argument("--build", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    image = load_image(args.dll)

    tables = {}
    for filename in sorted(os.listdir(args.cdir)):
        if not filename.endswith(".c"):
            continue
        opcode = int(filename[:-2], 16)
        with open(os.path.join(args.cdir, filename), encoding="utf-8", errors="replace") as handle:
            text = handle.read()
        for match in TABLE.finditer(text):
            address, index_var = int(match.group(1), 16), match.group(2)
            bound = None
            for b in BOUND.finditer(text[:match.start()]):
                if b.group(1) == index_var:
                    bound = int(b.group(2), 0)
            if bound is None or bound > 64:
                continue
            values = []
            for i in range(bound):
                ptr, length = struct.unpack_from("<II", image.data, image.offset(address + 8 * i))
                values.append(image.string(ptr) or "?")
            tables.setdefault(opcode, []).append({"table_va": f"{address:#010x}", "index_var": index_var,
                                                  "count": bound, "values": values})

    with open(args.out, "w", encoding="utf-8") as out:
        print("# Generated by tools/extract/result_tables.py -- do not hand-edit.", file=out)
        print(f"build: {args.build}", file=out)
        print(f"sha256: {hashlib.sha256(image.data).hexdigest()}", file=out)
        print("# Per opcode: the string tables its handler indexes by a value read from the packet,", file=out)
        print("# with the bound it checks first. Value i of the field means values[i].", file=out)
        print(f"opcodes: {len(tables)}", file=out)
        print("tables:", file=out)
        for opcode in sorted(tables):
            print(f"  {opcode:#06x}:", file=out)
            for table in tables[opcode]:
                print(f"    - table_va: \"{table['table_va']}\"", file=out)
                print(f"      index_var: {table['index_var']}   # the decompiled variable indexing it", file=out)
                print(f"      count: {table['count']}", file=out)
                print("      values:", file=out)
                for value in table["values"]:
                    print(f"        - \"{value}\"", file=out)
    print(f"{len(tables)} opcodes with result tables -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
